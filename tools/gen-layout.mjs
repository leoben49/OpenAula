// Regenerates src/lib/layout.ts from the official driver's layout file.
// Usage: node tools/gen-layout.mjs "C:/Program Files (x86)/AULA F75 Max Gasket Mechanical Keyboard/layouts/rgb-keyboard.xml"
import { readFileSync, writeFileSync } from 'node:fs';

const xml = readFileSync(process.argv[2], 'utf8');
const LABELS = {
  Shift_L: 'Shift', Shift_R: 'Shift', Ctrl_L: 'Ctrl', Win_L: 'Win', Alt_L: 'Alt', Alt_R: 'Alt',
  delete: 'Del', 'page up': 'PgUp', 'page down': 'PgDn', end: 'End', CapsLock: 'Caps', '}}': '}]',
  '&amp;7': '&7', '"\'': '"\'',
  '↑': '↑', '←': '←', '↓': '↓', '→': '→',
};
const attr = (s, name) => s.match(new RegExp(`\\b${name}="([^"]*)"`))?.[1] ?? '';
const rows = [...xml.matchAll(/<key [^>]*\/>/g)].map(([s]) => {
  const raw = attr(s, 'name').replace(/&quot;/g, '"').replace(/&amp;/g, '&');
  const label = LABELS[raw] ?? raw;
  return [+attr(s, 'key_index'), parseInt(attr(s, 'code'), 16), +attr(s, 'rect_left') - 90, +attr(s, 'rect_top') - 28, +attr(s, 'rect_width'), label];
});
// The driver's file describes AULA's own edition (Alt + Fn right of the space
// bar). The EPOMAKER x AULA edition has Fn + Ctrl there, wired to slots 96 and
// 98 (found by remapping slots 95–98 on a real board; 95 and 97 are unwired).
const alt = rows.findIndex((r) => r[0] === 95);
const fn = rows.findIndex((r) => r[0] === 96);
if (alt !== -1 && fn !== -1) {
  const [, , altX, y, w] = rows[alt];
  const fnX = rows[fn][2];
  rows[fn] = [96, 0xaf, altX, y, w, 'Fn'];
  rows[alt] = [98, 0xe4, fnX, y, w, 'Ctrl'];
}
rows.sort((a, b) => a[3] - b[3] || a[2] - b[2]);

const fmt = ([i, u, x, y, w, l]) => `  [${i}, 0x${u.toString(16).padStart(2, '0')}, ${x}, ${y}, ${w}, ${JSON.stringify(l)}],`;

writeFileSync(
  'src/lib/layout.ts',
  `/**
 * F75 Max physical layout, generated by tools/gen-layout.mjs from the official
 * driver's layout file: [key index, default HID usage, x, y, width, label] in
 * the driver's pixel grid (keys are 30 px tall). The key index addresses the
 * keymap and per-key colour tables.
 */
export interface Key {
  index: number;
  usage: number;
  x: number;
  y: number;
  w: number;
  label: string;
}

const RAW: [number, number, number, number, number, string][] = [
${rows.map(fmt).join('\n')}
];

export const KEYS: Key[] = RAW.map(([index, usage, x, y, w, label]) => ({ index, usage, x, y, w, label }));
export const KEY_HEIGHT = 30;
export const LAYOUT_WIDTH = Math.max(...KEYS.map((k) => k.x + k.w));
export const LAYOUT_HEIGHT = Math.max(...KEYS.map((k) => k.y)) + KEY_HEIGHT;
export const FN_INDEX = 96;
`,
);
console.log(`${rows.length} keys`);
